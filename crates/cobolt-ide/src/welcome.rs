//! Localised quote pool for the welcome pane. Each language has its own set so
//! the rotating quote follows the IDE's selected language. Every language
//! carries the FULL pool, in the same order as English, so no quote is ever
//! missing from one language or shown in another (scripture references are
//! localised, e.g. `Proverbs` → `Proverbios`).

use crate::i18n::Language;

/// `(author, quote)` pairs.
type Quote = (&'static str, &'static str);

/// The quote pool for `lang`.
pub fn quotes(lang: Language) -> &'static [Quote] {
    match lang {
        Language::Spanish => ES,
        Language::Portuguese => PT,
        Language::Japanese => JA,
        Language::Chinese => ZH,
        Language::English => EN,
        Language::French => FR,
    }
}

