#[cfg(test)]
mod tests {
    use super::*;
    use crate::i18n::Language;

    #[test]
    fn every_language_has_a_nonempty_localized_pool() {
        for lang in [
            Language::English,
            Language::Spanish,
            Language::Portuguese,
            Language::Japanese,
            Language::Chinese,
            Language::French,
        ] {
            let q = quotes(lang);
            assert!(!q.is_empty(), "{lang:?} quote pool is empty");
            // No entry may be blank.
            assert!(
                q.iter().all(|(a, t)| !a.is_empty() && !t.is_empty()),
                "{lang:?} has a blank quote/author"
            );
        }
        // Every language carries the whole pool, in English's order.
        let en = quotes(Language::English);
        for lang in [Language::Spanish, Language::Portuguese, Language::Japanese, Language::Chinese, Language::French] {
            let q = quotes(lang);
            assert_eq!(q.len(), en.len(), "{lang:?} is missing quotes");
            for ((ea, et), (a, t)) in en.iter().zip(q) {
                // Scripture keeps its chapter and verse; people keep their name.
                let reference = |r: &str| r.rsplit(' ').next().map(str::to_owned);
                if ea.contains(':') {
                    assert_eq!(reference(ea), reference(a), "{lang:?}: {ea} vs {a}");
                } else {
                    assert_eq!(ea, a, "{lang:?}: author order differs");
                }
                assert_ne!(et, t, "{lang:?}: {ea} is not translated");
            }
        }
        // Non-English pools must actually differ from English (localised).
        assert_ne!(
            quotes(Language::Spanish)[0].1,
            quotes(Language::English)[0].1
        );
        assert_ne!(
            quotes(Language::French)[0].1,
            quotes(Language::English)[0].1
        );
    }
}
