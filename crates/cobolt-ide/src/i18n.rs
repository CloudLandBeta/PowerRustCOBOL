//! Internationalisation — UI string translations.
//!
//! Every piece of user-visible text in the IDE and Form Designer interface is
//! stored here.  COBOL data-item names, generated source code, and
//! programmatic diagnostic messages are intentionally **not** translated.
//!
//! # Supported languages
//! - English  🇺🇸
//! - Español  🇪🇸
//! - Português 🇧🇷
//! - 日本語   🇯🇵
//! - 中文     🇨🇳

// ── Language ──────────────────────────────────────────────────────────────────

/// Selected UI language.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Language {
    #[default]
    English,
    Spanish,
    Portuguese,
    Japanese,
    Chinese,
    French,
}

impl Language {
    /// All variants in display order.
    pub const ALL: &'static [Language] = &[
        Language::English,
        Language::Portuguese,
        Language::Spanish,
        Language::French,
        Language::Japanese,
        Language::Chinese,
    ];

    /// Name shown in the language selector — written in the language itself.
    /// The flag beside it is *painted* (see [`crate::flags`]), not an emoji:
    /// egui does not ligate regional-indicator pairs, so "🇧🇷" came out as `B R`.
    pub fn native_name(self) -> &'static str {
        match self {
            Language::English => "English",
            Language::Spanish => "Español",
            Language::Portuguese => "Português",
            Language::Japanese => "日本語",
            Language::Chinese => "中文",
            Language::French => "Français",
        }
    }

    /// Stable short code used to persist the choice (see [`crate::ui_prefs`]).
    /// Independent of the doc-file suffixes in `docs_embed`, which follow the
    /// guide filenames (`jp`, `cn`) rather than the language tags.
    pub fn code(self) -> &'static str {
        match self {
            Language::English => "en",
            Language::Spanish => "es",
            Language::Portuguese => "pt",
            Language::Japanese => "ja",
            Language::Chinese => "zh",
            Language::French => "fr",
        }
    }

    /// Inverse of [`Language::code`]; `None` for anything unrecognised, so a
    /// hand-edited or future preferences file cannot break startup.
    pub fn from_code(code: &str) -> Option<Self> {
        Language::ALL
            .iter()
            .copied()
            .find(|l| l.code().eq_ignore_ascii_case(code.trim()))
    }

    /// Return the full translation table for this language.
    pub fn tr(self) -> Tr {
        match self {
            Language::English => EN,
            Language::Spanish => ES,
            Language::Portuguese => PT,
            Language::Japanese => JA,
            Language::Chinese => ZH,
            Language::French => FR,
        }
    }
}

/// Store the active language in egui context so modals can retrieve it.
pub fn set_language(ctx: &egui::Context, lang: Language) {
    ctx.data_mut(|d| d.insert_temp(egui::Id::new("cobolt-ui-lang"), lang as u8));
}

/// Retrieve the active Tr table from egui context.
pub fn current_tr(ctx: &egui::Context) -> Tr {
    let lang_byte = ctx
        .data(|d| d.get_temp::<u8>(egui::Id::new("cobolt-ui-lang")))
        .unwrap_or(0);
    let lang = match lang_byte {
        1 => Language::Spanish,
        2 => Language::Portuguese,
        3 => Language::Japanese,
        4 => Language::Chinese,
        5 => Language::French,
        _ => Language::English,
    };
    lang.tr()
}

