//! **The native project of a Mobile project** (WASM-012 R16–R18, WASM-INDEX D22; Q7 decided as
//! the spec recommends): the Android Studio project a Mobile project keeps in its own folder,
//! `android/`, beside `mobileforms/` and `backend/`.
//!
//! It is the mobile shell staged as a package build stages it ([`mobile_build::stage`]): the
//! shell's Rust source (`shell/`), the application crate (`src-tauri/`), the Web bundle
//! (`frontend/`), and the Gradle project the Tauri command line generates for them,
//! `android/src-tauri/gen/android` — the folder Android Studio opens, whose project carries the
//! application's name. Nothing in it is written by hand and nothing of the application is in it
//! but the bundle: no COBOL, no form, no secret (R18). While it exists every package build
//! brings it up to date with the same bundle and the same sources ([`refresh_android`]), so what
//! Android Studio runs is what the package shows. The IDE's own package builds keep their staging
//! in the build folder: a Build never waits on Android Studio's caches, nor Android Studio on the
//! IDE's.

use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Child, Command, Stdio};

use crate::mobile_build::{self as mb, AndroidAbi, Checked, Missing, PackageRequest, Toolchain};
use crate::project_kind::MobilePlatform;

/// The native Android project's folder in the project.
pub const ANDROID_DIR: &str = "android";

/// The native iOS project's folder in the project (Q7), which this version does not make yet.
pub const IOS_DIR: &str = "ios";

/// The Gradle project inside it: the folder Android Studio opens.
pub const ANDROID_STUDIO_SUBDIR: &str = "src-tauri/gen/android";

/// What a version-control system should leave out of `android/`: what the tools build and cache.
pub const ANDROID_GITIGNORE: &str = "# Generated by PowerRustCOBOL AI (WASM-012 R16): what the tools build and cache.\n\
src-tauri/target/\n\
src-tauri/gen/android/.gradle/\n\
src-tauri/gen/android/.idea/\n\
src-tauri/gen/android/build/\n\
src-tauri/gen/android/app/build/\n\
src-tauri/gen/android/local.properties\n\
src-tauri/gen/android/app/src/main/jniLibs/\n\
src-tauri/.cargo/\n";

/// The end of the line that names the Gradle project.
const NAME_MARKER: &str = "// PowerRustCOBOL AI: the project's name (WASM-012 R16)";

/// `settings.gradle` with the Gradle project named `name` — what Android Studio shows for it
/// (R16: named as the PowerRustCOBOL AI project). The Tauri command line writes no name, so
/// Android Studio would call it after its folder, `android`. A name written before is replaced.
pub fn patch_project_name(settings: &str, name: &str) -> String {
    let quoted = name.replace('\\', "\\\\").replace('\'', "\\'");
    let line = format!("rootProject.name = '{quoted}' {NAME_MARKER}");
    let kept: Vec<&str> = settings.lines().filter(|l| !l.ends_with(NAME_MARKER)).collect();
    format!("{line}\n{}\n", kept.join("\n").trim_end())
}

/// Name the Gradle project in `studio_dir` after the project.
fn name_project(studio_dir: &Path, name: &str) -> Result<(), String> {
    let path = studio_dir.join("settings.gradle");
    let text = std::fs::read_to_string(&path).map_err(|e| format!("{} cannot be read ({e})", path.display()))?;
    mb::write_if_changed(&path, patch_project_name(&text, name).as_bytes())
}

/// `android/` of the project in `project_dir`.
pub fn android_root(project_dir: &Path) -> PathBuf {
    project_dir.join(ANDROID_DIR)
}

/// The folder Android Studio opens.
pub fn android_studio_dir(project_dir: &Path) -> PathBuf {
    android_root(project_dir).join(ANDROID_STUDIO_SUBDIR)
}

/// The project in `project_dir` has its Android Studio project (the Gradle project the Tauri
/// command line generated is there).
pub fn android_exists(project_dir: &Path) -> bool {
    android_studio_dir(project_dir).join("app/build.gradle.kts").is_file()
}

/// What [`create_android`] made.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Created {
    /// The Android Studio project, in this folder.
    Ready(PathBuf),
    /// The shell's sources only: this computer lacks what generating the Gradle project needs
    /// (R16: the project files it can, and the missing tools named). Creating it again once they
    /// are installed finishes it.
    SourcesOnly(Vec<Missing>),
}

/// `req` with the native project as its staging folder.
fn native_request(req: &PackageRequest) -> PackageRequest {
    let mut r = req.clone();
    r.staging_dir = android_root(&req.project_dir);
    r
}

/// Create the Android Studio project of the Mobile project `req` describes (or make it again over
/// the one there): stage the shell into `android/`, then — when this computer has the tools —
/// have the Tauri command line generate the Gradle project, make the edits a package build makes
/// (orientation, signing hook, the names under the icon) and the launcher icons. The project
/// needs its application id (R6); its bundle may come later, with the first Build.
pub fn create_android(req: &PackageRequest, log: &mut dyn FnMut(&str)) -> Result<Created, String> {
    if req.settings.platform != MobilePlatform::Android {
        return Err("the project's platform is iOS; an Android Studio project is made for an Android project".to_owned());
    }
    let r = native_request(req);
    let checked = mb::check_shell(&r).map_err(|p| p.join("\n"))?;
    log(&format!("Creating the Android Studio project in {}", r.staging_dir.display()));
    let staged = mb::stage(&r, &checked)?;
    mb::write_if_changed(&r.staging_dir.join(".gitignore"), ANDROID_GITIGNORE.as_bytes())?;
    let tools = match Toolchain::detect(req.abi) {
        Ok(t) => t,
        Err(missing) => return Ok(Created::SourcesOnly(missing)),
    };
    if !staged.android_dir.join("app/build.gradle.kts").is_file() {
        mb::run_logged(&staged.app_dir, &["tauri", "android", "init", "--ci", "--skip-targets-install"], &tools, &[], log)?;
    }
    mb::patch_android_project(&staged, &r)?;
    name_project(&staged.android_dir, &req.project_name)?;
    write_cargo_config(&staged.app_dir, &tools.ndk_home, checked.android_min_sdk)?;
    let icon = staged.icon.to_string_lossy().into_owned();
    mb::run_logged(&staged.app_dir, &["tauri", "icon", &icon], &tools, &[], log)?;
    Ok(Created::Ready(staged.android_dir))
}

/// Bring the project's Android Studio project, when it has one, up to date with what a package
/// build has just checked and staged: the same bundle as `frontend/`, the same sources, the same
/// edits (R16, R18), and the linking settings for `tools`' NDK. Nothing is run — Android Studio's
/// Gradle builds it when the developer runs it. `Ok(false)`: the project has none.
pub fn refresh_android(req: &PackageRequest, checked: &Checked, tools: &Toolchain) -> Result<bool, String> {
    if !android_exists(&req.project_dir) {
        return Ok(false);
    }
    let r = native_request(req);
    let staged = mb::stage(&r, checked)?;
    mb::patch_android_project(&staged, &r)?;
    if staged.android_dir.join("settings.gradle").is_file() {
        name_project(&staged.android_dir, &req.project_name)?;
    }
    write_cargo_config(&staged.app_dir, &tools.ndk_home, checked.android_min_sdk)?;
    mb::write_if_changed(&r.staging_dir.join(".gitignore"), ANDROID_GITIGNORE.as_bytes())?;
    Ok(true)
}

/// The Android Rust targets, with the name of their compiler in the NDK.
const ANDROID_TARGETS: [(&str, &str); 4] = [
    ("aarch64-linux-android", "aarch64-linux-android"),
    ("armv7-linux-androideabi", "armv7a-linux-androideabi"),
    ("i686-linux-android", "i686-linux-android"),
    ("x86_64-linux-android", "x86_64-linux-android"),
];

/// What Cargo links an Android library with: the NDK's `clang` for the API level `min_sdk`, and the
/// system libraries the shell needs.
const ANDROID_RUSTFLAGS: &str = "[\"-Clink-arg=-landroid\", \"-Clink-arg=-llog\", \"-Clink-arg=-lOpenSLES\"]";

/// `src-tauri/.cargo/config.toml` of the native project: for every Android target, the linker and
/// the flags the Tauri command line gives Cargo itself (Tauri 2.12.4 `configure_cargo`). Found on
/// 2026-11-07: `tauri android build` passes them in its own environment, which reaches Gradle only
/// when it runs Gradle itself, but the script Android Studio's Gradle build runs
/// (`android-studio-script`) sets neither, so in Android Studio Cargo linked with the computer's
/// `cc` and failed — and built every library again, its flags differing. Written here, Cargo
/// reads them whatever started Android Studio, with the same flags as the package build's.
pub fn cargo_config(ndk_home: &Path, min_sdk: u32) -> String {
    let prebuilt = ndk_home.join("toolchains/llvm/prebuilt");
    let host = std::fs::read_dir(&prebuilt)
        .ok()
        .and_then(|d| d.flatten().filter(|e| e.path().is_dir()).map(|e| e.file_name().to_string_lossy().into_owned()).min())
        .unwrap_or_else(|| {
            let os = if cfg!(target_os = "macos") { "darwin" } else if cfg!(windows) { "windows" } else { "linux" };
            format!("{os}-x86_64")
        });
    let suffix = if cfg!(windows) { ".cmd" } else { "" };
    let mut text = String::from(
        "# Generated by PowerRustCOBOL AI (WASM-012 R16) for this computer's Android NDK: how Cargo links the\n\
         # application when Android Studio's Gradle build runs it. Written again by every package build.\n",
    );
    for (triple, clang) in ANDROID_TARGETS {
        let linker = prebuilt.join(&host).join("bin").join(format!("{clang}{min_sdk}-clang{suffix}"));
        let quoted = linker.to_string_lossy().replace('\\', "\\\\").replace('"', "\\\"");
        text.push_str(&format!("\n[target.{triple}]\nlinker = \"{quoted}\"\nrustflags = {ANDROID_RUSTFLAGS}\n"));
    }
    text
}

/// Write [`cargo_config`] into the native project's application crate `app_dir`.
fn write_cargo_config(app_dir: &Path, ndk_home: &Path, min_sdk: u32) -> Result<(), String> {
    let dir = app_dir.join(".cargo");
    std::fs::create_dir_all(&dir).map_err(|e| format!("{} cannot be created ({e})", dir.display()))?;
    mb::write_if_changed(&dir.join("config.toml"), cargo_config(ndk_home, min_sdk).as_bytes())
}

/// The arguments of the Tauri command line that Android Studio's builds of the project talk to
/// (found with Tauri 2.12.4: the Gradle project builds the shell through
/// `tauri android android-studio-script`, which asks a running `tauri android build` or
/// `tauri android dev` for its options and fails without one). This one builds the debug package
/// once for `abi`, opens Android Studio on the project and keeps running until it is stopped.
pub fn studio_args(abi: AndroidAbi) -> [&'static str; 8] {
    ["android", "build", "--ci", "--debug", "--apk", "--target", abi.tauri_target(), "--open"]
}

/// The Tauri command line's own program. It is started directly, not as `cargo tauri`: through
/// cargo it would run as cargo's child, which stopping cargo leaves running.
pub fn cargo_tauri() -> PathBuf {
    let exe = if cfg!(windows) { "cargo-tauri.exe" } else { "cargo-tauri" };
    let on_path: Vec<PathBuf> = std::env::var_os("PATH").map(|p| std::env::split_paths(&p).map(|d| d.join(exe)).collect()).unwrap_or_default();
    let cargo_home = std::env::var_os("CARGO_HOME").map(PathBuf::from);
    let home = std::env::var_os("HOME").or_else(|| std::env::var_os("USERPROFILE")).map(|h| PathBuf::from(h).join(".cargo"));
    let homes = cargo_home.into_iter().chain(home).map(|h| h.join("bin").join(exe));
    on_path.into_iter().chain(homes).find(|p| p.is_file()).unwrap_or_else(|| PathBuf::from(exe))
}

/// Start the native project's Rust build from the package build's, on macOS, when it has none:
/// a clone (`cp -c`, the file system's copy-on-write) takes no room until one of them changes,
/// and the libraries the two share are not built again — the first Open in Android Studio then
/// builds the application's own crates only. Elsewhere a copy would take gigabytes, so the first
/// one builds everything. Nothing is cloned over a build that is there.
pub fn seed_rust_build(from: &Path, to: &Path, log: &mut dyn FnMut(&str)) {
    if !cfg!(target_os = "macos") || to.exists() || !from.is_dir() {
        return;
    }
    if let Some(parent) = to.parent() {
        let _ = std::fs::create_dir_all(parent);
    }
    match Command::new("/bin/cp").arg("-cR").arg(from).arg(to).stdin(Stdio::null()).stdout(Stdio::null()).stderr(Stdio::null()).status() {
        Ok(s) if s.success() => log(&format!("Rust build started from the package build's: {}", from.display())),
        _ => {
            // A partial clone would be a build Cargo cannot trust: it builds afresh instead.
            let _ = std::fs::remove_dir_all(to);
        }
    }
}

/// Open the project's Android Studio project in Android Studio (WASM-012 R16, AC12), with what
/// its builds need while the developer works there: bring it up to date as Create does
/// ([`create_android`]), start its Rust build from the package build's in `req.staging_dir`
/// ([`seed_rust_build`]), then start the Tauri command line of [`studio_args`] in
/// `android/src-tauri`. The answer is that process: Android Studio's Run builds through it while it
/// runs; kill it to stop. Every line — the update's and the command line's — goes to `log_path`.
pub fn open_android_studio(req: &PackageRequest, log_path: &Path) -> Result<Child, String> {
    if let Some(dir) = log_path.parent() {
        std::fs::create_dir_all(dir).map_err(|e| format!("{} cannot be created ({e})", dir.display()))?;
    }
    let mut file = std::fs::File::create(log_path).map_err(|e| format!("{} cannot be written ({e})", log_path.display()))?;
    let mut log = |line: &str| {
        let _ = writeln!(file, "{line}");
    };
    let how = |missing: Vec<Missing>| missing.into_iter().map(|m| m.how).collect::<Vec<_>>().join("; ");
    if let Created::SourcesOnly(missing) = create_android(req, &mut log)? {
        return Err(how(missing));
    }
    let tools = Toolchain::detect(req.abi).map_err(how)?;
    let app_dir = android_root(&req.project_dir).join("src-tauri");
    seed_rust_build(&req.staging_dir.join("src-tauri/target"), &app_dir.join("target"), &mut log);
    let program = cargo_tauri();
    let args = studio_args(req.abi);
    log(&format!("$ {} {}", program.display(), args.join(" ")));
    let out = file.try_clone().map_err(|e| e.to_string())?;
    let err = file.try_clone().map_err(|e| e.to_string())?;
    let mut cmd = Command::new(&program);
    cmd.args(args).current_dir(&app_dir).stdin(Stdio::null()).stdout(out).stderr(err);
    for (k, v) in tools.env() {
        cmd.env(k, v);
    }
    // The native project keeps its own Rust build, as the staging folder does.
    cmd.env_remove("CARGO_TARGET_DIR");
    cmd.spawn().map_err(|e| format!("the Tauri command line ({}) could not be started ({e})", program.display()))
}
