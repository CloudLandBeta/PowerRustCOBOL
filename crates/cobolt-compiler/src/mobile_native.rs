//! **The native project of a Mobile project** (WASM-012 R16–R18, WASM-INDEX D22; Q7 decided as
//! the spec recommends): the Android Studio project a Mobile project keeps in its own folder,
//! `android/`, beside `mobileforms/` and `backend/`.
//!
//! It is the mobile shell staged as a package build stages it ([`mobile_build::stage`]): the
//! shell's Rust source (`shell/`), the application crate (`src-tauri/`), the Web bundle
//! (`frontend/`), and the Gradle project the Tauri command line generates for them,
//! `android/src-tauri/gen/android` — the folder Android Studio opens, whose project carries the
//! application's name. Nothing in it is written by hand and nothing of the application is in it
//! but the bundle: no COBOL, no form, no secret (R18). While it exists every package build
//! brings it up to date with the same bundle and the same sources ([`refresh_android`]), so what
//! Android Studio runs is what the package shows. The IDE's own package builds keep their staging
//! in the build folder: a Build never waits on Android Studio's caches, nor Android Studio on the
//! IDE's.

use std::path::{Path, PathBuf};

use crate::mobile_build::{self as mb, Checked, Missing, PackageRequest, Toolchain};
use crate::project_kind::MobilePlatform;

/// The native Android project's folder in the project.
pub const ANDROID_DIR: &str = "android";

/// The native iOS project's folder in the project (Q7), which this version does not make yet.
pub const IOS_DIR: &str = "ios";

/// The Gradle project inside it: the folder Android Studio opens.
pub const ANDROID_STUDIO_SUBDIR: &str = "src-tauri/gen/android";

/// What a version-control system should leave out of `android/`: what the tools build and cache.
pub const ANDROID_GITIGNORE: &str = "# Generated by PowerRustCOBOL AI (WASM-012 R16): what the tools build and cache.\n\
src-tauri/target/\n\
src-tauri/gen/android/.gradle/\n\
src-tauri/gen/android/.idea/\n\
src-tauri/gen/android/build/\n\
src-tauri/gen/android/app/build/\n\
src-tauri/gen/android/local.properties\n\
src-tauri/gen/android/app/src/main/jniLibs/\n";

/// The end of the line that names the Gradle project.
const NAME_MARKER: &str = "// PowerRustCOBOL AI: the project's name (WASM-012 R16)";

/// `settings.gradle` with the Gradle project named `name` — what Android Studio shows for it
/// (R16: named as the PowerRustCOBOL AI project). The Tauri command line writes no name, so
/// Android Studio would call it after its folder, `android`. A name written before is replaced.
pub fn patch_project_name(settings: &str, name: &str) -> String {
    let quoted = name.replace('\\', "\\\\").replace('\'', "\\'");
    let line = format!("rootProject.name = '{quoted}' {NAME_MARKER}");
    let kept: Vec<&str> = settings.lines().filter(|l| !l.ends_with(NAME_MARKER)).collect();
    format!("{line}\n{}\n", kept.join("\n").trim_end())
}

/// Name the Gradle project in `studio_dir` after the project.
fn name_project(studio_dir: &Path, name: &str) -> Result<(), String> {
    let path = studio_dir.join("settings.gradle");
    let text = std::fs::read_to_string(&path).map_err(|e| format!("{} cannot be read ({e})", path.display()))?;
    mb::write_if_changed(&path, patch_project_name(&text, name).as_bytes())
}

/// `android/` of the project in `project_dir`.
pub fn android_root(project_dir: &Path) -> PathBuf {
    project_dir.join(ANDROID_DIR)
}

/// The folder Android Studio opens.
pub fn android_studio_dir(project_dir: &Path) -> PathBuf {
    android_root(project_dir).join(ANDROID_STUDIO_SUBDIR)
}

/// The project in `project_dir` has its Android Studio project (the Gradle project the Tauri
/// command line generated is there).
pub fn android_exists(project_dir: &Path) -> bool {
    android_studio_dir(project_dir).join("app/build.gradle.kts").is_file()
}

/// What [`create_android`] made.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Created {
    /// The Android Studio project, in this folder.
    Ready(PathBuf),
    /// The shell's sources only: this computer lacks what generating the Gradle project needs
    /// (R16: the project files it can, and the missing tools named). Creating it again once they
    /// are installed finishes it.
    SourcesOnly(Vec<Missing>),
}

/// `req` with the native project as its staging folder.
fn native_request(req: &PackageRequest) -> PackageRequest {
    let mut r = req.clone();
    r.staging_dir = android_root(&req.project_dir);
    r
}

/// Create the Android Studio project of the Mobile project `req` describes (or make it again over
/// the one there): stage the shell into `android/`, then — when this computer has the tools —
/// have the Tauri command line generate the Gradle project, make the edits a package build makes
/// (orientation, signing hook, the names under the icon) and the launcher icons. The project
/// needs its application id (R6); its bundle may come later, with the first Build.
pub fn create_android(req: &PackageRequest, log: &mut dyn FnMut(&str)) -> Result<Created, String> {
    if req.settings.platform != MobilePlatform::Android {
        return Err("the project's platform is iOS; an Android Studio project is made for an Android project".to_owned());
    }
    let r = native_request(req);
    let checked = mb::check_shell(&r).map_err(|p| p.join("\n"))?;
    log(&format!("Creating the Android Studio project in {}", r.staging_dir.display()));
    let staged = mb::stage(&r, &checked)?;
    mb::write_if_changed(&r.staging_dir.join(".gitignore"), ANDROID_GITIGNORE.as_bytes())?;
    let tools = match Toolchain::detect(req.abi) {
        Ok(t) => t,
        Err(missing) => return Ok(Created::SourcesOnly(missing)),
    };
    if !staged.android_dir.join("app/build.gradle.kts").is_file() {
        mb::run_logged(&staged.app_dir, &["tauri", "android", "init", "--ci", "--skip-targets-install"], &tools, &[], log)?;
    }
    mb::patch_android_project(&staged, &r)?;
    name_project(&staged.android_dir, &req.project_name)?;
    let icon = staged.icon.to_string_lossy().into_owned();
    mb::run_logged(&staged.app_dir, &["tauri", "icon", &icon], &tools, &[], log)?;
    Ok(Created::Ready(staged.android_dir))
}

/// Bring the project's Android Studio project, when it has one, up to date with what a package
/// build has just checked and staged: the same bundle as `frontend/`, the same sources, the same
/// edits (R16, R18). Nothing is run — Android Studio's Gradle builds it when the developer runs
/// it. `Ok(false)`: the project has none.
pub fn refresh_android(req: &PackageRequest, checked: &Checked) -> Result<bool, String> {
    if !android_exists(&req.project_dir) {
        return Ok(false);
    }
    let r = native_request(req);
    let staged = mb::stage(&r, checked)?;
    mb::patch_android_project(&staged, &r)?;
    if staged.android_dir.join("settings.gradle").is_file() {
        name_project(&staged.android_dir, &req.project_name)?;
    }
    Ok(true)
}
